// Generators: one function per output. Pure (strings in, strings out) so tests can check them
// without touching the file system; scripts/build.ts writes them to dist/.
import { ANIMA_COLORS, ANIMA_NUMBERS, animaNumberVar } from "./anima";
import { animaColors, animaNumbers, base, density, icon, palette, themes, type AnimaColor, type ThemeName } from "./source";

export const THEME_NAMES = Object.keys(themes) as ThemeName[];
export { ANIMA_COLORS, ANIMA_NUMBERS, animaNumberVar };
/** The Theme model also has `motion` (0 or 1), written by the bridge from the motion preference. */
export const ANIMA_RUNTIME_NUMBERS = ["motion"] as const;

const REF = /\{([a-z0-9.-]+)\}/g;
const cssName = (ref: string) => `--onyx-${ref.replace(/^palette\./, "palette-")}`;

/** A token value as CSS: references become var(--onyx-…), so Onyx's own rebinding keeps working. */
export const toCss = (value: string) => value.replace(REF, (_, ref: string) => `var(${cssName(ref)})`);

/** Every token of one theme as a flat map name → raw value (references unresolved). */
export function themeTable(theme: ThemeName, dens: keyof typeof density = "compact"): Record<string, string> {
  const t = themes[theme];
  const table: Record<string, string> = {};
  for (const [k, v] of Object.entries(palette)) table[`palette.${k}`] = v;
  Object.assign(table, base, density[dens], t.colors, "overrides" in t ? t.overrides : {});
  return table;
}

/** A token resolved to a literal for one theme ("palette.black", "control-button-bg", …). */
export function resolve(theme: ThemeName, name: string, seen: string[] = []): string {
  const table = themeTable(theme);
  const value = table[name];
  if (value === undefined) throw new Error(`unknown token "${name}" (theme ${theme})`);
  if (seen.includes(name)) throw new Error(`reference cycle: ${[...seen, name].join(" → ")}`);
  return value.replace(REF, (_, ref: string) => resolve(theme, ref, [...seen, name]));
}

/** Every --onyx-* variable name Golem emits (palette, base, density, every theme key). */
export function onyxVariableNames(): string[] {
  const names = new Set<string>();
  for (const k of Object.keys(palette)) names.add(`--onyx-palette-${k}`);
  for (const k of Object.keys(base)) names.add(`--onyx-${k}`);
  for (const k of Object.keys(density.compact)) names.add(`--onyx-${k}`);
  for (const k of Object.keys(themes.dark.colors)) names.add(`--onyx-${k}`);
  return [...names];
}

const block = (selector: string, vars: Record<string, string>, extra = "") =>
  `  ${selector} {\n${Object.entries(vars).map(([k, v]) => `    ${k}: ${toCss(v)};`).join("\n")}${extra}\n  }`;
const prefixed = (m: Record<string, string>, p = "--onyx-") =>
  Object.fromEntries(Object.entries(m).map(([k, v]) => [p + k, v]));

/**
 * Onyx CSS variables for every theme. Import after Onyx's (or @bedrock/ui's) styles.css: the
 * golem.tokens layer is declared after onyx.base, so it wins over Onyx's defaults while app CSS
 * (unlayered) still wins over both. Dark is also the :root default, as in Onyx.
 */
export function onyxCss(): string {
  const out: string[] = ["/* Generated by @mroiban/golem from packages/golem/src/tokens/source.ts. Do not edit. */",
    "@layer onyx.base, onyx.components, golem.tokens;", "@layer golem.tokens {"];
  out.push(block(":root", { ...prefixed(palette, "--onyx-palette-"), ...prefixed(base) }));
  out.push(block(":root,\n  [data-density='compact']", prefixed(density.compact)));
  out.push(block("[data-density='comfortable']", prefixed(density.comfortable)));
  for (const name of THEME_NAMES) {
    const t = themes[name];
    const selector = name === "dark" ? ":root,\n  [data-theme='dark']" : `[data-theme='${name}']`;
    // Aliases of other tokens are repeated in every theme block (as Onyx does) so a theme set on a
    // subtree resolves them against its own colours, not the root's.
    const aliases = Object.fromEntries(Object.entries(base).filter(([, v]) => /\{(?!palette\.)/.test(v)));
    const vars = { ...prefixed(aliases), ...prefixed(t.colors), ...prefixed("overrides" in t ? t.overrides : {}) };
    out.push(block(selector, vars, `\n    color-scheme: ${t.scheme};`));
  }
  out.push("}");
  return out.join("\n") + "\n";
}

/**
 * Anima colour slots: every Anima theme token as --anima-<token>, pointing at its Onyx variable.
 * Scenes that declare `<color name="<token>" value="…"/>` draw with var(--anima-<token>), so they
 * follow the page theme live, with no script and no first frame in the wrong colours.
 */
export function animaSlotsCss(selector = ".golem-anima, anima-icon"): string {
  const lines = ANIMA_COLORS.map((k) => `    --anima-${k}: var(${cssName(animaColors[k])});`);
  // Anima's numeric theme values per theme, read by the Theme data bridge.
  const numbers = THEME_NAMES.map((t) => {
    const sel = t === "dark" ? ":root,\n  [data-theme='dark']" : `[data-theme='${t}']`;
    return `  ${sel} {\n${ANIMA_NUMBERS.map((k) => `    ${animaNumberVar(k)}: ${animaNumbers[k][t]};`).join("\n")}\n  }`;
  });
  return `/* Generated by @mroiban/golem. Do not edit. */\n@layer golem.tokens {\n  ${selector} {\n${lines.join("\n")}\n  }\n${numbers.join("\n")}\n}\n`;
}

/** Resolved hex values of every Anima colour, per theme (for the Theme data model bridge). */
export function animaThemeValues(): Record<ThemeName, Record<AnimaColor, string> & Record<string, number | string>> {
  return Object.fromEntries(THEME_NAMES.map((t) => {
    const colors = Object.fromEntries(ANIMA_COLORS.map((k) => [k, resolve(t, animaColors[k]).toLowerCase()]));
    const numbers = Object.fromEntries(ANIMA_NUMBERS.map((k) => [k, animaNumbers[k][t]]));
    return [t, { ...colors, ...numbers }];
  })) as never;
}

const HEX = /^#[0-9a-f]{6}$/i;

/**
 * The AniML Theme library (anima-kit's onyx-theme.animl, generated). Defaults are the dark theme,
 * so a control drawn before the page writes its tokens (an off-screen host) is never black.
 */
export function animaThemeLibrary(defaultTheme: ThemeName = "dark"): string {
  const values = animaThemeValues()[defaultTheme];
  const colours = ANIMA_COLORS.map((k) => {
    const v = values[k] as string;
    if (!HEX.test(v)) throw new Error(`Anima colour ${k} must resolve to #rrggbb, got ${v}`);
    return `    <color name="${k}" default="${v}"/>`;
  });
  const numbers = ANIMA_NUMBERS.map((k) => {
    const all = THEME_NAMES.map((t) => animaNumbers[k][t]);
    return `    <number name="${k}" default="${values[k]}" min="${Math.min(0, ...all)}" max="${Math.max(...all)}"/>`;
  });
  return `<!-- Generated by @mroiban/golem. Do not edit. -->
<library name="golem-theme" export="Theme">
  <model name="Theme">
${colours.join("\n")}
${numbers.join("\n")}
    <number name="motion" default="1" min="0" max="1"/>
  </model>
</library>
`;
}

/**
 * Glyphy style targets: the [style] table of glyphy.toml. Keys are locked so `glyphy measure`
 * keeps Golem's values. Merge into a Glyphy project's glyphy.toml (or `glyphy set style.<k>=<v>`).
 */
export function glyphyStyle(): string {
  const keys = Object.keys(icon);
  const lines = Object.entries(icon).map(([k, v]) => `${k} = ${Number.isInteger(v) && k === "grid" ? v : v.toFixed(2)}`);
  return `# Generated by @mroiban/golem. Golem's icon geometry, in grid units.\n[style]\n${lines.join("\n")}\nlocked = [${keys.map((k) => `"${k}"`).join(", ")}]\n`;
}

/** Every generated file, by path under dist/. */
export function outputs(): Record<string, string> {
  return {
    "golem.css": onyxCss(),
    "anima-slots.css": animaSlotsCss(),
    "golem-theme.animl": animaThemeLibrary(),
    "anima-themes.json": JSON.stringify(animaThemeValues(), null, 2) + "\n",
    "glyphy-style.toml": glyphyStyle(),
  };
}
