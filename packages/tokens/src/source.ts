export type ThemeKey = keyof typeof darkColors;
export type ThemeTokens = Record<ThemeKey, string>;
export type Theme = {
  name: string;
  label: string;
  scheme: "light" | "dark";
  /** Every theme key (colours, shadows, overlays). */
  colors: ThemeTokens;
  /** Optional overrides of base tokens (component tier), e.g. a rounder button. */
  overrides?: Partial<Record<keyof typeof base, string>>;
};

